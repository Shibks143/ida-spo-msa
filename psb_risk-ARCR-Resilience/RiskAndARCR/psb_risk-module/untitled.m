midrVals = 0.2:0.2:4.0;

riskVals = [ ...
    0.024764
    0.0084314
    0.0043247
    0.0025851
    0.0017167
    0.0012339
    0.00093067
    0.00072999
    0.00059098
    0.00049172
    0.00043751
    0.00037097
    0.00032382
    0.00028486
    0.00024926
    0.00021770
    0.00019218
    0.00017152
    0.00015494
    0.00014127 ];

figure('Color','w');

%% Main risk curve
semilogy(midrVals, riskVals, '-o', ...
    'LineWidth', 1.8, ...
    'MarkerSize', 7, ...
    'MarkerFaceColor', 'b');

hold on;

%% Code-based target risk lines

lambda_10in50 = -log(1-0.10)/50;   % ≈ 2.1e-3
lambda_2in50  = -log(1-0.02)/50;   % ≈ 4.0e-4
lambda_collapse = 1e-4;

yline(lambda_10in50, '--r', ...
    'LineWidth', 1.0);

yline(lambda_2in50, '--r', ...
    'LineWidth', 1.0);

yline(lambda_collapse, '--r', ...
    'LineWidth', 1.0);

%% LEFT AXIS

yyaxis left

set(gca,'YScale','log');

ylabel('Annual Frequency of Exceedance, \lambda (1/year)', ...
    'FontSize',18, ...
    'Color','b');

ylim([1e-5 1e-1]);

%% RIGHT AXIS (Return Period)

yyaxis right

set(gca,'YScale','log');

ylim([1e-5 1e-1]);

% Return periods shown in figure
TR_ticks = [10000 2475 1000 475 100 50 10];

lambda_ticks = 1 ./ TR_ticks;

set(gca, ...
    'YTick', lambda_ticks, ...
    'YTickLabel', compose('%,g',TR_ticks), ...
    'YColor','r');

ylabel('Return Period, T_R (years)', ...
    'FontSize',18, ...
    'Color','r', ...
    'Rotation',270);

%% X-axis

xlabel('MIDR (%)', ...
    'FontSize',18);

xlim([0.2 4.0]);

%% Grid

grid on;
grid minor;

%% Title

title('Continuous Seismic Risk Curve in Drift Space', ...
    'FontSize',24, ...
    'FontWeight','normal');

%% Legend

yyaxis left

legend({'Annual Frequency of Exceedance', ...
         '\lambda (MIDR > x)'}, ...
         'Location','southwest', ...
         'FontSize',14);

%% Text annotations

text(3.3, lambda_10in50*1.2, ...
    '$T_R = 50$ years', ...
    'Interpreter','latex', ...
    'Color','r', ...
    'FontSize',18);

text(3.3, lambda_10in50*0.85, ...
    '(\lambda = 0.02/year)', ...
    'Color','r', ...
    'FontSize',14);

text(3.2, lambda_2in50*1.4, ...
    '$T_R = 475$ years', ...
    'Interpreter','latex', ...
    'Color','r', ...
    'FontSize',18);

text(3.2, lambda_2in50*0.85, ...
    '(\lambda = 0.002105/year)', ...
    'Color','r', ...
    'FontSize',14);

text(3.2, lambda_collapse*0.8, ...
    '$T_R = 2475$ years', ...
    'Interpreter','latex', ...
    'Color','r', ...
    'FontSize',18);

text(3.2, lambda_collapse*0.55, ...
    '(\lambda = 0.000404/year)', ...
    'Color','r', ...
    'FontSize',14);

%% Bottom textbox

annotation('textbox', ...
    [0.22 0.02 0.56 0.05], ...
    'String', ...
    'Left Y-axis: Annual Frequency of Exceedance (\lambda)   |   Right Y-axis: Return Period (T_R = 1/\lambda)', ...
    'FitBoxToText','on', ...
    'HorizontalAlignment','center', ...
    'FontSize',14, ...
    'BackgroundColor',[0.97 0.95 0.85]);

%% Final formatting

set(gca,'FontSize',16);
